// Safe bridge for the Tasks window.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('tasksApi', {
  get: () => ipcRenderer.invoke('tasks:get'),
  add: (task) => ipcRenderer.invoke('tasks:add', task),
  complete: (id) => ipcRenderer.invoke('tasks:complete', id),
  remove: (id) => ipcRenderer.invoke('tasks:delete', id),
  clearOverdue: () => ipcRenderer.invoke('tasks:clear-overdue'),
  focus: (id) => ipcRenderer.invoke('tasks:focus', id),
  stopFocus: () => ipcRenderer.invoke('tasks:stop-focus'),
  openUrl: (url) => ipcRenderer.invoke('tasks:open-url', url),
  setCalendar: (urls) => ipcRenderer.invoke('conn:set-calendar', urls),
  setGithub: (token) => ipcRenderer.invoke('conn:set-github', token),
  disconnectGithub: () => ipcRenderer.invoke('conn:disconnect-github'),
  importGithub: () => ipcRenderer.invoke('conn:import-github'),
  remindersLists: () => ipcRenderer.invoke('conn:reminders-lists'),
  remindersSave: (lists) => ipcRenderer.invoke('conn:reminders-save', lists),
  remindersDisconnect: () => ipcRenderer.invoke('conn:reminders-disconnect'),
  setTodoist: (token) => ipcRenderer.invoke('conn:set-todoist', token),
  disconnectTodoist: () => ipcRenderer.invoke('conn:disconnect-todoist'),
  setCompleteInSource: (on) => ipcRenderer.invoke('conn:complete-in-source', on),
  syncNow: () => ipcRenderer.invoke('conn:sync-now'),
  onUpdate: (cb) => ipcRenderer.on('tasks:update', (_e, view) => cb(view)),
  onTab: (cb) => ipcRenderer.on('hub:tab', (_e, tab) => cb(tab)),
  equip: (id) => ipcRenderer.invoke('hub:equip', id),
  vacation: (on) => ipcRenderer.invoke('hub:vacation', on),
  retire: () => ipcRenderer.invoke('hub:retire'),
  play: (id) => ipcRenderer.invoke('hub:play', id),
  saveSettings: (input) => ipcRenderer.invoke('hub:save-settings', input),
  copyDebug: () => ipcRenderer.invoke('debug:copy'),
  checkinSubmit: (items) => ipcRenderer.invoke('checkin:submit', items),
  checkinSkip: () => ipcRenderer.invoke('checkin:skip'),
  lightsOff: () => ipcRenderer.invoke('pet:lights'),
  medicine: () => ipcRenderer.invoke('pet:medicine'),
  reset: (mode) => ipcRenderer.invoke('hub:reset', mode),
  letRest: () => ipcRenderer.invoke('hub:let-rest'),
  testNotify: () => ipcRenderer.invoke('notify:test'),
  openLog: () => ipcRenderer.invoke('debug:open-log'),
  setupChecks: () => ipcRenderer.invoke('setup:checks'),
  setupTest: (id) => ipcRenderer.invoke('setup:test', id),
  setupFix: (kind) => ipcRenderer.invoke('setup:fix', kind),
  setupDone: (input) => ipcRenderer.invoke('setup:done', input),
  setupAgain: () => ipcRenderer.invoke('setup:again'),
  openMess: (kind) => ipcRenderer.invoke('hub:open-mess', kind),
  takeBreak: (minutes) => ipcRenderer.invoke('focus:break', minutes),
  endBreak: () => ipcRenderer.invoke('focus:end-break'),
  checkNow: () => ipcRenderer.invoke('focus:check'),
  neverDistracting: (source) => ipcRenderer.invoke('focus:never', source),
  setStrict: (on) => ipcRenderer.invoke('focus:strict', on),
  reopenTabs: () => ipcRenderer.invoke('focus:reopen-tabs'),
  openTab: (url) => ipcRenderer.invoke('focus:open-tab', url),
  clearTabs: () => ipcRenderer.invoke('focus:clear-tabs'),
  startFocus: (minutes) => ipcRenderer.invoke('focus:start', minutes),
});
