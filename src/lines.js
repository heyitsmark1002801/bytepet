function say(key, vars = {}) {
  const arr = LINES[key];
  if (!arr || !arr.length) return null;
  return pick(arr).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

function sayForApp(appName) {
  const arr = LINES.app[appName];
  return arr ? pick(arr) : null;
}

